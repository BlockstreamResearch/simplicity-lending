export const AVERAGE_BLOCK_TIME_SECONDS = 60
export const SECONDS_PER_MINUTE = 60
export const MINUTES_PER_HOUR = 60
const HOURS_PER_DAY = 24
const DAYS_PER_YEAR = 365
export const MINUTES_PER_DAY = HOURS_PER_DAY * MINUTES_PER_HOUR
export const BLOCKS_PER_HOUR = (MINUTES_PER_HOUR * SECONDS_PER_MINUTE) / AVERAGE_BLOCK_TIME_SECONDS
export const BLOCKS_PER_DAY = HOURS_PER_DAY * BLOCKS_PER_HOUR
export const BLOCKS_PER_YEAR = DAYS_PER_YEAR * BLOCKS_PER_DAY
