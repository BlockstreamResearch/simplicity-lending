ALTER TABLE offer_participants ADD COLUMN id BIGINT;

-- Order existing rows by height; within a block, rows spent in that same block go first.
UPDATE offer_participants AS p
SET id = ordered.rn
FROM (
    SELECT
        txid,
        vout,
        row_number() OVER (
            ORDER BY
                created_at_height,
                (spent_at_height = created_at_height) DESC NULLS LAST,
                txid,
                vout
        ) AS rn
    FROM offer_participants
) AS ordered
WHERE p.txid = ordered.txid
  AND p.vout = ordered.vout;

-- A higher id is a later NFT move: rows must be inserted in transaction processing order.
ALTER TABLE offer_participants
    ALTER COLUMN id SET NOT NULL,
    ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY,
    ADD UNIQUE (id);

SELECT setval(
    pg_get_serial_sequence('offer_participants', 'id'),
    COALESCE((SELECT MAX(id) FROM offer_participants), 0) + 1,
    false
);

